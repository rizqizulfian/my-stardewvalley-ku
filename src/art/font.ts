export const GLYPHS: Readonly<Record<string, readonly string[]>> = G;

export function glyphWidth(ch: string): number {
  if (ch === ' ') return FONT.spaceWidth;
  return (GLYPHS[ch] ?? GLYPHS['?'])[0].length;
}

export function measureText(text: string): number {
  let w = 0;
  for (const ch of text) w += glyphWidth(ch) + FONT.spacing;
  return Math.max(0, w - FONT.spacing);
}

/** Greedy word wrap to a pixel width. */
export function wrapText(text: string, maxWidth: number): string[] {
  const lines: string[] = [];
  for (const para of text.split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const next = line ? `${line} ${word}` : word;
      if (measureText(next) > maxWidth && line) {
        lines.push(line);
        line = word;
      } else line = next;
    }
    lines.push(line);
  }
  return lines;
}

/** Bake a line of text into a palette grid (used for painted signs). */
export function textGrid(text: string, color: ColorName): PixelGrid {
  const g = new PixelGrid(Math.max(1, measureText(text)), FONT.height);
  let x = 0;
  for (const ch of text) {
    if (ch !== ' ') {
      const rows = GLYPHS[ch] ?? GLYPHS['?'];
      rows.forEach((row, ry) => {
        for (let rx = 0; rx < row.length; rx++) if (row[rx] === '#') g.set(x + rx, ry, color);
      });
    }
    x += glyphWidth(ch) + FONT.spacing;
  }
  return g;
}
